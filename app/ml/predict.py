"""Inference helpers for the trained URL classifier.

The trained artefact is a dictionary produced by :mod:`app.ml.train`::

    {
      "model": <fitted sklearn Pipeline>,
      "model_name": "RandomForest",
      "feature_names": [...],
      "feature_means": [...],
      "feature_stds": [...],
      "direction": [...],        # sign of the logistic-regression coefficients
      "importances": [...],      # per-feature importance of the selected model
      "metrics": {...},
      "trained_at": "ISO-8601",
      "dataset": {...}
    }
"""

from __future__ import annotations

import os
from functools import lru_cache
from pathlib import Path

from app.ml.feature_engineering import FEATURE_NAMES, extract_features

DEFAULT_MODEL_PATH = Path(__file__).resolve().parent / "model.joblib"


class ModelNotAvailable(RuntimeError):
    """Raised when no trained model artefact can be loaded."""


#: Single source of truth for the model honesty statement, reused by every
#: surface that publishes a score (prediction payload, metadata, API, UI).
DISCLAIMER = (
    "Model output is a statistical estimate produced from URL string features. "
    "It can be wrong in both directions and must not be treated as certainty."
)


def model_digest(path: str | os.PathLike) -> str:
    """SHA-256 of the model artefact."""
    import hashlib

    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _verify_integrity(path: str) -> str:
    """Check the artefact against a recorded digest before loading it.

    ``joblib.load`` unpickles, which executes code. The artefact that ships is
    built locally by ``train.py`` from a committed CSV, so it is trustworthy -
    but a *swapped* file would be arbitrary code execution with no warning at
    all. ``app/ml/model.sha256`` pins the expected digest.

    Deliberately a warning rather than a hard failure: ``python train.py``
    legitimately rewrites the model, and refusing to start after a retrain
    would be worse than the risk. A mismatch is loud and auditable; the file
    is regenerated by the trainer, so drift is expected and explainable.
    Set ML_REQUIRE_INTEGRITY=1 to make a mismatch fatal instead.
    """
    import logging
    import os as _os

    expected_file = Path(path).with_suffix(".sha256")
    actual = model_digest(path)
    if not expected_file.exists():
        return actual
    expected = expected_file.read_text(encoding="utf-8").split()[0].strip()
    if expected and expected != actual:
        message = (f"ML model integrity mismatch for {path}: expected "
                   f"{expected[:16]}... got {actual[:16]}... "
                   f"Re-run 'python train.py' to regenerate both, or restore "
                   f"the committed artefact.")
        if _os.environ.get("ML_REQUIRE_INTEGRITY", "").strip() in ("1", "true", "yes"):
            raise RuntimeError(message)
        logging.getLogger("phishguard.security").warning(
            "ml.integrity_mismatch", extra={
                "event": "security", "action": "ml_integrity_mismatch",
                "outcome": "WARNING", "actor": None, "resource": str(path),
                "extra_fields": {"expected_prefix": expected[:16],
                                 "actual_prefix": actual[:16]},
            })
    return actual


@lru_cache(maxsize=4)
def _load_bundle(path: str, mtime: float):  # mtime busts the cache after retraining
    import joblib

    _verify_integrity(path)
    return joblib.load(path)


def load_model(path: str | os.PathLike | None = None) -> dict:
    """Load (and memoise) the trained model bundle."""
    model_path = Path(path or DEFAULT_MODEL_PATH)
    if not model_path.exists():
        raise ModelNotAvailable(
            f"No trained model at {model_path}. Run 'python -m app.ml.train' to create it."
        )
    return _load_bundle(str(model_path), model_path.stat().st_mtime)


def model_available(path: str | os.PathLike | None = None) -> bool:
    return Path(path or DEFAULT_MODEL_PATH).exists()


def _attribution(bundle: dict, vector: list[float], top_n: int = 6) -> list[dict]:
    """Approximate per-feature attribution for a single prediction.

    contribution ~= importance x z-score x direction

    ``direction`` is the sign of the logistic-regression coefficient, so a
    positive contribution pushes the sample towards the phishing class.  This
    is a transparent linear approximation - it is *not* an exact Shapley value
    and is labelled as approximate everywhere it is displayed.
    """
    names = bundle.get("feature_names", FEATURE_NAMES)
    means = bundle.get("feature_means") or [0.0] * len(names)
    stds = bundle.get("feature_stds") or [1.0] * len(names)
    importances = bundle.get("importances") or [1.0] * len(names)
    direction = bundle.get("direction") or [1.0] * len(names)

    rows = []
    for idx, name in enumerate(names):
        std = stds[idx] if idx < len(stds) and stds[idx] else 1.0
        mean = means[idx] if idx < len(means) else 0.0
        value = vector[idx] if idx < len(vector) else 0.0
        z = (value - mean) / std
        contribution = float(importances[idx]) * z * float(direction[idx])
        if abs(contribution) < 1e-9:
            continue
        rows.append({
            "feature": name,
            "value": round(float(value), 4),
            "z_score": round(float(z), 3),
            "contribution": round(float(contribution), 5),
            "pushes": "phishing" if contribution > 0 else "legitimate",
        })
    rows.sort(key=lambda r: abs(r["contribution"]), reverse=True)
    return rows[:top_n]


def predict_url(url: str, model_path: str | os.PathLike | None = None) -> dict:
    """Classify a single URL.

    Returns a JSON-serialisable dict with the classification, a 0-100 risk
    score, the model's confidence, the extracted features and an approximate
    per-feature explanation.  Confidence is a model probability, not a
    guarantee of correctness.
    """
    bundle = load_model(model_path)
    model = bundle["model"]
    features = extract_features(url)
    vector = features.vector()

    proba = None
    if hasattr(model, "predict_proba"):
        proba = float(model.predict_proba([vector])[0][1])
    else:  # pragma: no cover - all shipped models expose predict_proba
        proba = float(model.predict([vector])[0])

    label = "PHISHING" if proba >= 0.5 else "LEGITIMATE"
    confidence = proba if label == "PHISHING" else 1.0 - proba

    return {
        "url": features.url,
        "classification": label,
        "risk_score": round(proba * 100, 2),
        "probability_phishing": round(proba, 4),
        "confidence": round(confidence, 4),
        "model": bundle.get("model_name", "unknown"),
        "trained_at": bundle.get("trained_at"),
        "features": features.as_dict()["numeric"],
        "explanation": _attribution(bundle, vector),
        "disclaimer": DISCLAIMER,
    }


def predict_batch(urls, model_path: str | os.PathLike | None = None) -> list[dict]:
    bundle = load_model(model_path)
    model = bundle["model"]
    vectors = [extract_features(u).vector() for u in urls]
    probabilities = model.predict_proba(vectors)[:, 1]
    results = []
    for url, vector, proba in zip(urls, vectors, probabilities):
        label = "PHISHING" if proba >= 0.5 else "LEGITIMATE"
        results.append({
            "url": url,
            "classification": label,
            "risk_score": round(float(proba) * 100, 2),
            "confidence": round(float(proba if label == "PHISHING" else 1 - proba), 4),
            "model": bundle.get("model_name", "unknown"),
        })
    return results


def model_metadata(model_path: str | os.PathLike | None = None) -> dict:
    """Return metrics/metadata for the loaded artefact (for the UI + API)."""
    try:
        bundle = load_model(model_path)
    except ModelNotAvailable:
        return {"available": False}
    return {
        "available": True,
        "model_name": bundle.get("model_name"),
        "trained_at": bundle.get("trained_at"),
        "metrics": bundle.get("metrics", {}),
        "dataset": bundle.get("dataset", {}),
        "feature_count": len(bundle.get("feature_names", FEATURE_NAMES)),
        # Both metadata surfaces (this one and MLDetector.metadata) must carry
        # the honesty text; otherwise a caller can present the metrics with no
        # indication of how dataset-dependent they are.
        "disclaimer": DISCLAIMER,
        "caveat": bundle.get("caveat", ""),
        "sklearn_version": bundle.get("sklearn_version"),
    }
